/**
 * Regenerates docs/domain/FINANCE-METRICS.md and docs/domain/CALCULATION-RULES.md from the
 * semantic layer seed (apps/cap/db/data). The docs are an output of the model, not a second
 * source of truth (G2-01). Run: npm run docs:semantic --workspace=apps/cap
 * A test fails if the committed docs drift from this output.
 */
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { SemanticCatalog } from '../srv/semantic/catalog.ts';
import { loadSeedRows } from '../srv/semantic/runtime.ts';

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '../../..');
export const DOC_PATHS = {
  metrics: resolve(repo, 'docs/domain/FINANCE-METRICS.md'),
  rules: resolve(repo, 'docs/domain/CALCULATION-RULES.md')
};

const HEADER = '<!-- GENERATED by apps/cap/scripts/generate-semantic-docs.ts from apps/cap/db/data. Do not edit by hand. -->\n';
const esc = (s: string | null | undefined) => String(s ?? '—').replace(/\|/g, '\\|');

export function renderMetricsDoc(c = new SemanticCatalog(loadSeedRows())): string {
  const ids = c.metricIds();
  let md = `${HEADER}# Finance metrics (semantic layer)\n\n`;
  md += 'Source of truth: the semantic layer tables (`apps/cap/db/semantic.cds`, seed in `apps/cap/db/data`). ';
  md += 'Every result records the metric version it used (for example `total_revenue@v1`).\n\n';
  md += '> A metric runs in **pilot** and **production** only with an APPROVED, effective version (and approved dependencies). ';
  md += 'In **mock** and **local** (synthetic data) a PENDING_REVIEW version may run so development works before Finance sign-off (decision D-02). REJECTED, RETIRED and DRAFT versions never run.\n\n';
  md += '## Catalog\n\n| Metric | Label | Category | Kind | Definition | Unit | Latest version | Status | Effective from | Owner |\n|---|---|---|---|---|---|---|---|---|---|\n';
  for (const id of ids) {
    const d = c.definition(id)!, v = c.latestVersion(id)!;
    const def = v.kind === 'DERIVED' ? `\`${v.expression}\`` : `signed sum of ${v.accountType} accounts (${v.signRule})`;
    md += `| \`${id}\` | ${esc(d.label)} | ${d.category} | ${v.kind} | ${def} | ${v.unit}, ${v.decimals} dp | v${v.version} | **${v.status}** | ${v.effectiveFrom} | ${esc(d.owner)} |\n`;
  }
  for (const id of ids) {
    const d = c.definition(id)!;
    md += `\n## \`${id}\` — ${d.label}\n\n${d.description}\n\n`;
    md += `- **Aliases (glossary):** ${c.aliases(id).map((a) => `“${a}”`).join(', ') || '—'}\n`;
    md += `- **Versions:** ${c.allVersions(id).map((v) => `v${v.version} ${v.status} (effective ${v.effectiveFrom}${v.approvedBy ? `, approved by ${v.approvedBy}` : ''})`).join('; ')}\n`;
    const deps = c.latestVersion(id)!.dependsOn;
    if (deps.length) md += `- **Depends on:** ${deps.map((x) => `\`${x}\``).join(', ')}\n`;
    md += '\n| Source system | Entity set | Field | Mapping status | Evidence |\n|---|---|---|---|---|\n';
    for (const l of c.lineage(id)) md += `| ${l.sourceSystem} | ${esc(l.entitySet)} | ${esc(l.field)} | ${l.mappingStatus} | ${esc(l.evidence)} |\n`;
  }
  const unsupported = c.rows.glossary.filter((g) => g.status === 'UNSUPPORTED').map((g) => g.term);
  md += `\n## Known terms that are not metrics yet\n\nThese are recognised and refused with an explanation (never guessed): ${unsupported.map((t) => `“${t}”`).join(', ')}.\n`;
  return md;
}

export function renderRulesDoc(c = new SemanticCatalog(loadSeedRows())): string {
  let md = `${HEADER}# Calculation rules\n\n`;
  md += '## Arithmetic and rounding (ADR-013, decision D-03)\n\n';
  md += '- All money and ratio arithmetic uses arbitrary-precision decimals (decimal.js). Binary floating point is never used for money; a test scans calculation code for float operations.\n';
  md += '- Provider amounts are converted through their string form.\n';
  md += '- Rounding: ROUND_HALF_UP (half away from zero), applied once per metric to its declared decimals. Derived metrics use the rounded values of their dependencies, as published figures do.\n\n';
  md += '## Base metrics (signed sums)\n\n| Metric | Account type | Positive side | Negative side |\n|---|---|---|---|\n';
  for (const id of c.metricIds()) {
    const v = c.latestVersion(id)!;
    if (v.kind !== 'BASE') continue;
    const credit = v.signRule === 'CREDIT_POSITIVE';
    md += `| \`${id}\` | ${v.accountType} | ${credit ? 'Credit (C)' : 'Debit (D)'} | ${credit ? 'Debit (D) — e.g. returns' : 'Credit (C) — e.g. refunds'} |\n`;
  }
  md += '\nSign conventions are UNCONFIRMED until Finance confirms them against SAP (G2-03).\n\n';
  md += '## Derived metrics (formula DAG)\n\n| Metric | Formula | Unit |\n|---|---|---|\n';
  for (const id of c.metricIds()) {
    const v = c.latestVersion(id)!;
    if (v.kind === 'DERIVED') md += `| \`${id}\` | \`${v.expression}\` | ${v.unit} |\n`;
  }
  md += '\nFormulas are parsed into a tree (numbers, metric ids, + − × ÷, parentheses); they are never executed as code. Dependencies must form a DAG: a proposal that creates a cycle is rejected when it is written.\n\n';
  md += '## Data quality rules\n\n';
  md += '- **Mixed currencies** in the records in scope: the calculation is refused (no conversion table is configured).\n';
  md += '- **Zero vs missing:** each result has a data state — AVAILABLE, ZERO_VALUE (records exist, value is zero) or MISSING_DATA (no records). Missing data is never presented as an ordinary 0.00.\n';
  md += '- **Division by zero** (for example profit margin with zero revenue) returns 0 with a zero-denominator flag.\n';
  md += '- **Duplicate record ids** are reported in the result\'s data-quality section.\n\n';
  const cal = c.fiscalCalendar('K4');
  if (cal) md += `## Fiscal calendar\n\n\`${cal.calendarId}\`: ${cal.description}. ${cal.periodsPerYear} posting periods + ${cal.specialPeriods} special periods; seeded years: ${[...new Set(cal.periods.map((p) => p.fiscalYear))].join(', ')}.\n`;
  return md;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(DOC_PATHS.metrics, renderMetricsDoc());
  writeFileSync(DOC_PATHS.rules, renderRulesDoc());
  console.log('wrote', DOC_PATHS.metrics, DOC_PATHS.rules);
}
