import { z } from 'zod';
import { MetricIdEnum, SupportedDimensionEnum } from './finance-metrics.js';
import { RequestFiltersSchema } from './dashboard-request.js';

/**
 * Data Plan Step Definition
 */
export const DataPlanStepSchema = z.object({
  stepNumber: z.number().int().positive(),
  action: z.literal('fetch_records'),
  tool: z.literal('get_finance_metrics'),
  targetMetrics: z.array(MetricIdEnum).min(1),
  dimensions: z.array(SupportedDimensionEnum),
  filters: RequestFiltersSchema.optional(),
  sourceType: z.enum(['mock', 's4hana']),
  estimatedRows: z.number().int().nonnegative().optional()
}).strict();
export type DataPlanStep = z.infer<typeof DataPlanStepSchema>;

/**
 * Versioned Execution Data Plan Schema (v1.0)
 * Generated by the Orchestrator/Planner to safely execute retrieval tools.
 */
export const DataPlanSchema = z.object({
  planVersion: z.literal('1.0').default('1.0'),
  planId: z.string().uuid(),
  requestId: z.string().optional(),
  organizationId: z.string().min(1),
  userId: z.string().min(1),
  status: z.enum(['PLANNED', 'VALIDATED', 'EXECUTING', 'COMPLETED', 'FAILED']),
  steps: z.array(DataPlanStepSchema).min(1),
  createdAt: z.string().datetime(),
  resolvedSource: z.enum(['mock', 's4hana']),
  rejectionReason: z.string().optional()
}).strict();
export type DataPlan = z.infer<typeof DataPlanSchema>;

